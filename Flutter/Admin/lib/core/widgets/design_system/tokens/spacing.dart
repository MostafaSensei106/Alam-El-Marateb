abstract final class AppSpacing {
  /// 4 logical pixels: tight spacing for compact layouts.
  static const double xSmall = 4;

  /// 8 logical pixels: spacing between closely related elements.
  static const double small = 8;

  /// 12 logical pixels: standard spacing within a component.
  static const double medium = 12;

  /// 16 logical pixels: comfortable spacing between elements.
  static const double large = 16;

  /// 24 logical pixels: spacing between component groups.
  static const double xLarge = 24;

  /// 32 logical pixels: spacing between major sections.
  static const double xxLarge = 32;

  /// 48 logical pixels: generous spacing for distinct page sections.
  static const double xxxLarge = 48;
}
